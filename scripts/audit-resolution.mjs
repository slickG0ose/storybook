#!/usr/bin/env node
/**
 * Generate docs/conventions/harness-resolution.md — a stable, diff-friendly
 * snapshot of project-tier harness configuration.
 *
 * Resolution tiers, highest precedence first:
 *   1. Project          .claude/             (this repo — SNAPSHOTTED)
 *   2. User             ~/.claude/           (per-machine — NOT snapshotted)
 *   3. Built-in         (opaque)             (Claude Code core + plugins)
 *
 * Why only project tier? The snapshot is meant to be byte-identical across
 * CI and every contributor's machine, so the regression gate stays
 * deterministic. Including the user tier (which varies per developer's
 * ~/.claude/) would dirty the snapshot on every dev's machine. The built-in
 * tier is opaque from the filesystem and can't be enumerated regardless.
 *
 * Two entry points:
 *   - CLI:  `node scripts/audit-resolution.mjs` writes the snapshot to disk
 *   - Test: `import { generateSnapshot } from './scripts/audit-resolution.mjs'`
 *           returns the markdown string for assertion against the committed
 *           file. See .claude/__tests__/references/resolution-snapshot.test.ts.
 */
import { readdirSync, readFileSync, existsSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const PROJECT_CLAUDE = path.join(REPO_ROOT, '.claude');
const OUT_PATH = path.join(REPO_ROOT, 'docs', 'conventions', 'harness-resolution.md');

// --- frontmatter parser (inlined; the test helper is TS) ---
const FM_RE = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/;
function parseFm(text) {
  const m = FM_RE.exec(text);
  if (!m) return {};
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const km = /^([a-zA-Z][a-zA-Z0-9_-]*)\s*:\s*(.*)$/.exec(line);
    if (!km) continue;
    let v = km[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    data[km[1]] = v;
  }
  return data;
}

function listMd(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
}

function listSkills(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((name) => {
    const p = path.join(dir, name, 'SKILL.md');
    try {
      return statSync(p).isFile();
    } catch {
      return false;
    }
  }).sort();
}

function listFiles(dir, ext) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith(ext)).sort();
}

/**
 * Build the harness-resolution.md content as a string. Pure read function —
 * no disk writes. Test code imports this and diffs against the committed
 * snapshot; the CLI shim below writes the result to disk.
 */
export function generateSnapshot() {
  const out = [];
  out.push('# Harness resolution snapshot');
  out.push('');
  out.push('> Generated by `npm run audit:resolution` (calls `scripts/audit-resolution.mjs`).');
  out.push('> ');
  out.push('> This is a **diff-friendly snapshot** of where every harness item is resolved from.');
  out.push('> Regenerate after harness changes and commit the diff.');
  out.push('> ');
  out.push('> The vitest suite (`.claude/__tests__/references/resolution-snapshot.test.ts`)');
  out.push('> re-derives this string and fails if it drifts from the committed file, so a');
  out.push('> stale snapshot is caught by `npm test` before push.');
  out.push('');
  out.push('## Resolution tiers');
  out.push('');
  out.push('Highest precedence first:');
  out.push('');
  out.push('| Tier | Location | Notes |');
  out.push('|------|----------|-------|');
  out.push('| Project | `.claude/` | This repo. Wins over user + built-in. |');
  out.push('| User | `~/.claude/` | Per-machine, per-user. Wins over built-in. |');
  out.push('| Built-in | (opaque) | Claude Code core + active plugins. Not enumerable from filesystem. |');
  out.push('');

  // NOTE on tier coverage: the committed snapshot enumerates ONLY the
  // project tier (`.claude/`). User-tier (`~/.claude/`) and built-in tier
  // contents are intentionally omitted because they vary by developer
  // machine — including them here would make every developer's regen produce
  // a different snapshot, defeating the regression check.

  // Agents
  out.push('## Agents');
  out.push('');
  const projAgents = listMd(path.join(PROJECT_CLAUDE, 'agents'));

  if (projAgents.length === 0) {
    out.push('_None at project tier. User and built-in tiers provide defaults (Plan, Explore, ...). See "User & built-in tiers" note at the bottom._');
  } else {
    out.push('| Name | Tier | Description |');
    out.push('|------|------|-------------|');
    for (const f of projAgents) {
      const fm = parseFm(readFileSync(path.join(PROJECT_CLAUDE, 'agents', f), 'utf8'));
      out.push(`| ${fm.name ?? path.basename(f, '.md')} | project | ${fm.description ?? ''} |`);
    }
  }
  out.push('');

  // Commands
  out.push('## Commands');
  out.push('');
  const projCmds = listMd(path.join(PROJECT_CLAUDE, 'commands'));

  out.push('| Name | Tier | Description |');
  out.push('|------|------|-------------|');
  for (const f of projCmds) {
    const fm = parseFm(readFileSync(path.join(PROJECT_CLAUDE, 'commands', f), 'utf8'));
    out.push(`| /${path.basename(f, '.md')} | project | ${fm.description ?? ''} |`);
  }
  out.push('');

  // Skills
  out.push('## Skills');
  out.push('');
  const projSkills = listSkills(path.join(PROJECT_CLAUDE, 'skills'));

  out.push('| Name | Tier | Mode | Description |');
  out.push('|------|------|------|-------------|');
  for (const name of projSkills) {
    const fm = parseFm(readFileSync(path.join(PROJECT_CLAUDE, 'skills', name, 'SKILL.md'), 'utf8'));
    out.push(`| ${name} | project | ${fm.mode ?? ''} | ${fm.description ?? ''} |`);
  }
  out.push('');

  // Hooks
  out.push('## Hooks');
  out.push('');
  out.push('| Script | Tier | Purpose |');
  out.push('|--------|------|---------|');
  for (const f of listFiles(path.join(PROJECT_CLAUDE, 'hooks'), '.sh')) {
    const head = readFileSync(path.join(PROJECT_CLAUDE, 'hooks', f), 'utf8').split(/\r?\n/, 5);
    // Use the first non-shebang, non-blank comment line as the purpose
    const purpose = head.find((l) => l.startsWith('#') && !l.startsWith('#!'))?.replace(/^#\s*/, '') ?? '';
    out.push(`| ${f} | project | ${purpose} |`);
  }
  out.push('');

  // Settings
  out.push('## Settings');
  out.push('');
  const settingsPath = path.join(PROJECT_CLAUDE, 'settings.json');
  if (existsSync(settingsPath)) {
    const s = JSON.parse(readFileSync(settingsPath, 'utf8'));
    out.push('### `permissions.allow`');
    out.push('');
    for (const entry of s.permissions?.allow ?? []) out.push(`- \`${entry}\``);
    out.push('');
    out.push(`**Default mode:** \`${s.permissions?.defaultMode ?? '(unset)'}\``);
    out.push('');
    out.push('### Hooks wired in settings');
    out.push('');
    for (const [event, slots] of Object.entries(s.hooks ?? {})) {
      for (const slot of slots) {
        const m = slot.matcher ? ` (matcher: \`${slot.matcher}\`)` : '';
        for (const h of slot.hooks) {
          out.push(`- **${event}**${m} → \`${h.command}\``);
        }
      }
    }
    out.push('');
    if (s.enabledPlugins) {
      out.push('### Enabled plugins');
      out.push('');
      for (const [plugin, enabled] of Object.entries(s.enabledPlugins)) {
        out.push(`- ${enabled ? '✓' : '✗'} \`${plugin}\``);
      }
      out.push('');
    }
  } else {
    out.push('_No `.claude/settings.json` at project tier._');
    out.push('');
  }

  // User & built-in tiers — explicitly NOT snapshotted
  out.push('## User & built-in tiers');
  out.push('');
  out.push('Contents at `~/.claude/` and the built-in tier are **not snapshotted** because they vary by developer machine. The committed snapshot covers only the project tier so the regression gate stays deterministic across CI and every contributor.');
  out.push('');
  out.push('To inspect your own resolution chain locally:');
  out.push('');
  out.push('```bash');
  out.push('ls ~/.claude/agents ~/.claude/commands ~/.claude/skills 2>/dev/null');
  out.push('cat ~/.claude/settings.json 2>/dev/null');
  out.push('```');
  out.push('');
  out.push('Built-in tier (opaque): Claude Code core ships agents (Plan, Explore, claude, general-purpose, claude-code-guide, statusline-setup, ...), skills (code-review, simplify, run, init, review, security-review, fewer-permission-prompts, loop, schedule, ...), and tools that are not enumerable from disk. They are available unless shadowed by a project- or user-tier item of the same name.');
  out.push('');

  return out.join('\n') + '\n';
}

/**
 * Where the committed snapshot lives. Exported so the test doesn't have to
 * duplicate the path.
 */
export const SNAPSHOT_PATH = OUT_PATH;

// --- CLI shim ---
// Two modes:
//   `node scripts/audit-resolution.mjs`            → write the snapshot to disk
//   `node scripts/audit-resolution.mjs --print`    → print the snapshot to stdout
//
// The --print mode is what the vitest test (.claude/__tests__/references/
// resolution-snapshot.test.ts) consumes via spawnSync. We took this route
// because vitest 4's transformer refuses to import a .mjs from a .ts test
// file (SyntaxError before any user code runs). Subprocess invocation
// sidesteps that entirely.
const isMain = import.meta.url === pathToFileURL(process.argv[1] ?? '').href;
if (isMain) {
  if (process.argv.includes('--print')) {
    process.stdout.write(generateSnapshot());
  } else {
    mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    writeFileSync(OUT_PATH, generateSnapshot());
    console.log(`Wrote ${path.relative(REPO_ROOT, OUT_PATH)}`);
  }
}
